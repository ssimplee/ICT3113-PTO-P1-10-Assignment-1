"""Summarise the Assignment 2 speed runs from each run's results.jtl and service log."""
import csv
import json
from datetime import datetime
from pathlib import Path
from statistics import mean

RUNS = Path(__file__).resolve().parent / "runs"
NAMES = {"llama3": "Llama 3B alone", "llama1": "Llama 1B alone", "qwen17": "Qwen 1.7B alone",
         "qwen06": "Qwen 0.6B alone", "cascade-a": "Cascade, Setting A (T = 223)",
         "cascade-b": "Cascade, Setting B (T = 142)"}


def percentile(values, fraction):
    # Same method as analyze_run.py: linear interpolation at (n-1)*p.
    ordered = sorted(values)
    position = (len(ordered) - 1) * fraction
    low = int(position)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] + (ordered[high] - ordered[low]) * (position - low)


def parse_utc(text):
    stamp, _, fraction = text.rstrip("Z").partition(".")
    return datetime.fromisoformat(f"{stamp}.{(fraction + '000000')[:6]}+00:00")


def analyze(folder):
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    with (folder / "results.jtl").open(encoding="utf-8", newline="") as stream:
        samples = list(csv.DictReader(stream))
    ready = json.loads((folder / "server-ready.json").read_text(encoding="utf-8-sig"))
    finish = json.loads((folder / "server-finish.json").read_text(encoding="utf-8-sig"))
    warmed = parse_utc(ready["captured_utc"])
    with (folder / "service-logs/requests.jsonl").open(encoding="utf-8") as stream:
        posts = [line for line in map(json.loads, stream) if line["method"] == "POST" and line["path"] == "/tickets"]
    in_run = [line for line in posts if parse_utc(line["timestamp"]) > warmed]
    assert len(posts) - len(in_run) == 3, f"{folder.name}: expected three warm-up tickets before the run"
    by_id = {line["request_id"]: line for line in in_run}
    completed = [s for s in samples if s["success"] == "true"]
    elapsed = [int(s["elapsed"]) / 1000 for s in completed]
    first_start = min(int(s["timeStamp"]) for s in samples)
    last_end = max(int(s["timeStamp"]) + int(s["elapsed"]) for s in samples)
    logged = [by_id[s["request_id"]] for s in completed if s["request_id"] in by_id]
    escalated = sum(bool(line["escalated"]) for line in logged)
    sent = max(len(samples), len(in_run))
    return dict(
        run_id=manifest["run_id"], folder=folder.name, configuration=manifest["configuration"],
        repeat=manifest["repeat"], sent=sent, completed=len(completed),
        errored=len(samples) - len(completed), unfinished=sent - len(samples),
        stored_by_service=finish["completed_and_stored"], matched_in_service_log=len(logged),
        warmup_posts=len(posts) - len(in_run), p50_s=percentile(elapsed, 0.5),
        min_s=min(elapsed), max_s=max(elapsed),
        throughput_per_s=len(completed) / ((last_end - first_start) / 1000),
        error_rate=(len(samples) - len(completed)) / sent,
        escalated=escalated if manifest["large_model_tag"] else None,
        elapsed_s=elapsed, rows=[s["row"] for s in sorted(samples, key=lambda s: int(s["timeStamp"]))])


def main():
    runs = []
    for manifest_path in sorted(RUNS.glob("*/manifest.json")):
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest["profile"] == "a2-speed" and (manifest_path.parent / "server-finish.json").exists():
            runs.append(analyze(manifest_path.parent))
    assert len({tuple(run["rows"]) for run in runs}) == 1, "Runs did not send the same tickets in the same order"
    summary, lines = {}, []
    lines += ["# Assignment 2 speed-test summary", "",
              "Generated by `jmeter/analyze_a2.py` from each run's `results.jtl`, `service-logs/requests.jsonl`,",
              "`server-ready.json` and `server-finish.json` under `jmeter/runs/`.", "",
              "## Per run", "",
              "| Configuration | Repeat | Folder | Sent | Completed | Errored | Unfinished | Stored by service | p50 (s) "
              "| Throughput (completed/s) | Error rate | Escalated |",
              "|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for key in NAMES:
        group = sorted((run for run in runs if run["configuration"] == key), key=lambda run: run["repeat"])
        if not group:
            continue
        for run in group:
            escalation = "–" if run["escalated"] is None else \
                f"{run['escalated']} of {run['completed']} ({run['escalated'] / run['completed']:.1%})"
            lines.append(f"| {NAMES[key]} | {run['repeat']} | `{run['folder']}` | {run['sent']} | {run['completed']} "
                         f"| {run['errored']} | {run['unfinished']} | {run['stored_by_service']} | {run['p50_s']:.2f} "
                         f"| {run['throughput_per_s']:.4f} | {run['error_rate']:.1%} | {escalation} |")
        pooled = [value for run in group for value in run["elapsed_s"]]
        p50s = [run["p50_s"] for run in group]
        summary[key] = dict(runs=len(group), p50_per_run_s=p50s, p50_mean_s=mean(p50s), p50_min_s=min(p50s),
                            p50_max_s=max(p50s), pooled_requests=len(pooled), pooled_p95_s=percentile(pooled, 0.95),
                            pooled_p50_s=percentile(pooled, 0.5), pooled_mean_s=mean(pooled),
                            escalated=None if group[0]["escalated"] is None else sum(run["escalated"] for run in group),
                            completed=sum(run["completed"] for run in group))
    reference = summary["llama3"]["p50_mean_s"]
    lines += ["", "## Per configuration", "",
              "| Configuration | Runs | p50 per run (s) | Mean of p50 (s) | Spread of p50 (s) | Against Llama 3B "
              "| Pooled p95 (s) | Requests in pooled p95 | Escalated, all runs |",
              "|---|---:|---|---:|---|---:|---:|---:|---:|"]
    for key, item in summary.items():
        escalation = "–" if item["escalated"] is None else \
            f"{item['escalated']} of {item['completed']} ({item['escalated'] / item['completed']:.1%})"
        against = "–" if key == "llama3" else f"{item['p50_mean_s'] / reference - 1:+.1%}"
        lines.append(f"| {NAMES[key]} | {item['runs']} | {', '.join(f'{v:.2f}' for v in item['p50_per_run_s'])} "
                     f"| {item['p50_mean_s']:.2f} | {item['p50_min_s']:.2f}–{item['p50_max_s']:.2f} | {against} "
                     f"| {item['pooled_p95_s']:.2f} | {item['pooled_requests']} | {escalation} |")
    lines += ["", "## Method", "",
              "- Latency is the JMeter `elapsed` time of successful requests. Percentiles use linear interpolation",
              "  at (n-1)*p, as in Assignment 1. p95 is computed on the three runs pooled; p99 is not reported.",
              "- Sent is the larger of the JMeter sample count and the service's POST count after warm-up.",
              "  Unfinished is sent minus JMeter samples.",
              "- Throughput is completed requests divided by the time from the first request sent to the last",
              "  response received.",
              "- Escalated counts `escalated: true` on the service log lines matched to JMeter by request ID.",
              "- Every run sent the same tickets in the same order; the same repeat number uses the same",
              "  arrival schedule in every configuration.", ""]
    (RUNS / "a2-speed-summary.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    for run in runs:
        del run["elapsed_s"], run["rows"]
    (RUNS / "a2-speed-summary.json").write_text(json.dumps(dict(runs=runs, configurations=summary), indent=2) + "\n",
                                                encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
